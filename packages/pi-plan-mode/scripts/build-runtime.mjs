#!/usr/bin/env node

import { execFile } from "node:child_process";
import { readdir, readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";
import { createRuntimeBuilder } from "../../../scripts/runtime-builder.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const exec = promisify(execFile);
const require = createRequire(import.meta.url);
const banner = [
  "// @generated by scripts/build-runtime.mjs; do not edit.",
  "// @ts-nocheck -- the generated entry uses a .ts extension for Pi's Jiti loader.",
].join("\n");
const forbiddenLibraryPackages = ["@earendil-works/pi-coding-agent", "@earendil-works/pi-tui", "@narumitw/pi-tui-kit"];
const runtime = createRuntimeBuilder({
  packageRoot,
  temporaryPrefix: ".pi-plan-mode",
  banner,
  forbiddenEagerInputs: [
    "src/interactive-ui.ts",
    "src/active-implementation-menu.ts",
    "src/plan-export-screen.ts",
    "src/plan-action-menus.ts",
    "src/plan-launch-menu.ts",
    "src/saved-plan-menu.ts",
    "src/settings-menu.ts",
  ],
  forbiddenEagerExternals: ["@narumitw/pi-tui-kit"],
});

export const { validateEagerGraph, publishRuntime } = runtime;

export async function buildRuntime({ outputDirectory, validateOutput } = {}) {
  return runtime.buildRuntime({
    outputDirectory,
    // The shared builder validates the Jiti graph first. Add the public library
    // inside the same staging directory, before its atomic publication.
    validateOutput: async (stagingDirectory) => {
      const library = await build({
        absWorkingDir: packageRoot,
        banner: { js: banner },
        bundle: true,
        chunkNames: "durable-chunks/[name]-[hash]",
        entryPoints: { durable: "src/durable.ts" },
        format: "esm",
        legalComments: "none",
        metafile: true,
        outdir: stagingDirectory,
        packages: "external",
        platform: "node",
        sourcemap: true,
        splitting: true,
        target: "es2022",
      });
      validateDurableGraph(library.metafile);
      await exec(process.execPath, [
        join(dirname(require.resolve("typescript")), "tsc.js"),
        "-p",
        join(packageRoot, "tsconfig.types.json"),
        "--outDir",
        stagingDirectory,
      ]);
      await validateGeneratedFiles(stagingDirectory);
      await validateOutput?.(stagingDirectory);
    },
  });
}

export function validateDurableGraph(metadata) {
  if (!Object.values(metadata.outputs ?? {}).some((output) => output.entryPoint === "src/durable.ts")) {
    throw new Error("Generated library metadata has no src/durable.ts entrypoint");
  }
  for (const output of Object.values(metadata.outputs ?? {})) {
    for (const input of Object.keys(output.inputs ?? {})) {
      const path = input.replaceAll("\\", "/");
      if (/(?:^|\/)node_modules\//u.test(path)) throw new Error(`Bundled package input: ${input}`);
      if (/(?:^|\/)src\/(?:state|plan-mode|extension-runtime)\.ts$/u.test(path)) {
        throw new Error(`Coding-agent source in durable library: ${input}`);
      }
    }
    for (const imported of output.imports ?? []) assertLibraryImport(imported.path);
  }
}

export async function validateGeneratedFiles(outputDirectory) {
  const files = await listFiles(outputDirectory);
  for (const required of ["index.ts", "index.ts.map", "durable.js", "durable.js.map", "durable.d.ts"]) {
    if (!files.includes(required)) throw new Error(`Generated runtime is missing ${required}`);
  }
  if (!files.some((file) => file.startsWith("chunks/") && file.endsWith(".ts"))) {
    throw new Error("Generated runtime has no lazy chunks");
  }
  for (const file of files.filter((path) => /\.(?:ts|js)$/u.test(path))) {
    const declaration = file.endsWith(".d.ts");
    const source = await readFile(join(outputDirectory, file), "utf8");
    if (!declaration) {
      if (!source.startsWith(banner)) throw new Error(`Generated marker is missing from ${file}`);
      if (!files.includes(`${file}.map`)) throw new Error(`Source map is missing for ${file}`);
    }
    if (declaration) {
      // Declarations contain erased imports, including import("...") types.
      for (const match of source.matchAll(/\b(?:from\s*|import\s*(?:\(\s*)?)["']([^"']+)["']/gu)) {
        validateImport(file, match[1], true, true);
      }
    }
  }
  // Parse runtime syntax without bundling, so comments and import-like text do
  // not affect the inventory of static, re-export, and dynamic imports.
  const parsed = await build({
    entryPoints: files
      .filter((file) => /\.(?:ts|js)$/u.test(file) && !file.endsWith(".d.ts"))
      .map((file) => resolve(outputDirectory, file)),
    outdir: resolve(outputDirectory, ".validation"),
    bundle: false,
    format: "esm",
    platform: "node",
    metafile: true,
    write: false,
  });
  for (const output of Object.values(parsed.metafile.outputs)) {
    const file = relative(outputDirectory, resolve(output.entryPoint)).replaceAll("\\", "/");
    for (const imported of output.imports) validateImport(file, imported.path, false, file.endsWith(".js"));
  }

  function validateImport(file, path, declaration, library) {
    if (library) assertLibraryImport(path);
    if (path.startsWith("./") || path.startsWith("../")) {
      const target = relative(outputDirectory, resolve(outputDirectory, dirname(file), path)).replaceAll("\\", "/");
      const expected = declaration ? target.replace(/\.js$/u, ".d.ts") : target;
      const extension = declaration ? ".d.ts" : library ? ".js" : ".ts";
      if (
        !expected.endsWith(extension) ||
        (!declaration && expected.endsWith(".d.ts")) ||
        !files.includes(expected) ||
        expected.startsWith("../")
      ) {
        throw new Error(`Generated relative import has no exact runtime target: ${path} from ${file}`);
      }
    }
  }
}

function assertLibraryImport(path) {
  if (forbiddenLibraryPackages.some((name) => path === name || path.startsWith(`${name}/`))) {
    throw new Error(`Coding-agent dependency in durable library: ${path}`);
  }
}

async function listFiles(directory, prefix = "") {
  const files = [];
  for (const entry of await readdir(join(directory, prefix), { withFileTypes: true })) {
    const path = join(prefix, entry.name).replaceAll("\\", "/");
    if (entry.isDirectory()) files.push(...(await listFiles(directory, path)));
    else if (entry.isFile()) files.push(path);
    else throw new Error(`Generated runtime contains a non-regular file: ${path}`);
  }
  return files.sort();
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : undefined;
if (invokedPath === import.meta.url) await buildRuntime();
